// #region Schema Version Compare

/** Editor Internal Schema table recording applied built-in migrations (`editor.schema_version`). */
export const editorSchemaVersionPhysicalTable = corePhysicalTableNameResolver.resolve('editor', 'schema_version');

const schemaVersionTableDdl = `CREATE TABLE IF NOT EXISTS ${quoteIdentifier(editorSchemaVersionPhysicalTable)} (`
	+ '"version" INTEGER NOT NULL PRIMARY KEY, "name" TEXT NOT NULL, "checksum" TEXT NOT NULL, "appliedAt" TEXT NOT NULL)';

export interface IAppliedEditorDdlMigration {
	readonly version: number;
	readonly name: string;
	readonly checksum: string;
	readonly appliedAt: string;
}

export interface IEditorSchemaVersion {
	/** Version recorded in `project.sqlite`; `0` before any migration was applied. */
	readonly current: number;
	/** Latest version known to this Editor. */
	readonly target: number;
	readonly applied: readonly IAppliedEditorDdlMigration[];
	/** `Unapplied Migration`, in apply order. */
	readonly unapplied: readonly IEditorDdlMigration[];
}

export async function readAppliedEditorDdlMigrations(database: IProjectSqliteStatements): Promise<readonly IAppliedEditorDdlMigration[]> {
	const table = await database.get(`SELECT name FROM sqlite_master WHERE type = 'table' AND name = ?`, [editorSchemaVersionPhysicalTable]);
	if (!table) {
		return Object.freeze([]);
	}
	const rows = await database.all(`SELECT "version", "name", "checksum", "appliedAt" FROM ${quoteIdentifier(editorSchemaVersionPhysicalTable)} ORDER BY "version"`);
	return Object.freeze(rows.map(row => Object.freeze({
		version: Number(row.version),
		name: String(row.name),
		checksum: String(row.checksum),
		appliedAt: String(row.appliedAt),
	})));
}

/**
 * `Schema Version Compare`: the applied migrations must be exactly the first versions of the
 * scanned resources, unchanged. A database written by a newer Editor (unknown version) or an
 * applied resource that was modified is rejected instead of being migrated.
 */
export function compareEditorSchemaVersion(migrations: readonly IEditorDdlMigration[], applied: readonly IAppliedEditorDdlMigration[]): IEditorSchemaVersion {
	applied.forEach((row, index) => {
		if (row.version !== index + 1) {
			throw new EditorDdlError(`project.sqlite Editor schema versions are not contiguous: expected ${index + 1}, found ${row.version}`);
		}
		const migration = migrations[index];
		if (!migration) {
			throw new EditorDdlError(`project.sqlite Editor schema version ${row.version} ('${row.name}') is newer than this Editor (latest ${migrations.length})`);
		}
		if (migration.name !== row.name || migration.checksum !== row.checksum) {
			throw new EditorDdlError(`Applied Editor DDL '${row.name}' (checksum ${row.checksum}) does not match resource '${migration.name}' (checksum ${migration.checksum})`);
		}
	});
	return Object.freeze({
		current: applied.length,
		target: migrations.length,
		applied,
		unapplied: Object.freeze(migrations.slice(applied.length)),
	});
}

export async function resolveEditorSchemaVersion(database: IProjectSqliteStatements, migrations: readonly IEditorDdlMigration[]): Promise<IEditorSchemaVersion> {
	assertProjectSqliteAccess(ProjectSqliteAccessor.Authoring);
	return compareEditorSchemaVersion(migrations, await readAppliedEditorDdlMigrations(database));
}

// #endregion

// #region SQLite Transaction -> Apply

/**
 * Applies every unapplied migration in one SQLite transaction and records each in
 * `editor__schema_version`. Any failure rolls back all of them. The schema version is compared
 * again inside the transaction so a concurrent writer cannot cause a double apply.
 */
export async function applyEditorDdlMigrations(database: IProjectSqliteDatabase, migrations: readonly IEditorDdlMigration[], resolved: IEditorSchemaVersion, now: () => Date = () => new Date()): Promise<readonly IAppliedEditorDdlMigration[]> {
	assertProjectSqliteAccess(ProjectSqliteAccessor.Authoring);
	if (!resolved.unapplied.length) {
		return Object.freeze([]);
	}
	return database.transaction(async tx => {
		const current = compareEditorSchemaVersion(migrations, await readAppliedEditorDdlMigrations(tx));
		if (current.current !== resolved.current) {
			throw new EditorDdlError(`project.sqlite Editor schema version changed during open: resolved ${resolved.current}, found ${current.current}`);
		}
		await tx.exec(schemaVersionTableDdl);
		const applied: IAppliedEditorDdlMigration[] = [];
		for (const migration of current.unapplied) {
			try {
				await tx.exec(migration.sql);
			} catch (error) {
				throw new EditorDdlError(`Editor DDL '${migration.name}' failed: ${error instanceof Error ? error.message : String(error)}`);
			}
			const row = Object.freeze({ version: migration.version, name: migration.name, checksum: migration.checksum, appliedAt: now().toISOString() });
			await tx.run(
				`INSERT INTO ${quoteIdentifier(editorSchemaVersionPhysicalTable)} ("version", "name", "checksum", "appliedAt") VALUES (?, ?, ?, ?)`,
				[row.version, row.name, row.checksum, row.appliedAt],
			);
			applied.push(row);
		}
		return Object.freeze(applied);
	});
}

