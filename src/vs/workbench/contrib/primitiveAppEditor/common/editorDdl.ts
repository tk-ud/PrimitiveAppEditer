// #region Open steps

/** Supplies the open `project.sqlite` (see `ProjectSqliteStorage`). */
export interface IEditorDdlDatabaseProvider {
	readonly database: IProjectSqliteDatabase;
}

/**
 * The `Editor DDL Scan` -> `Schema Version Resolve` -> `Migration Apply` steps of the project
 * `Open` lifecycle, run after `Create` / `Open` on the database opened by the storage step.
 * Each step requires the previous one; after `Migration Apply` the database is at the target
 * Editor schema version.
 */
export class EditorDdlMigrator implements Required<Pick<IProjectOpenSteps, 'editorDdlScan' | 'schemaVersionResolve' | 'migrationApply'>> {

	private _migrations: readonly IEditorDdlMigration[] | undefined;
	private _resolved: IEditorSchemaVersion | undefined;
	private _applied: readonly IAppliedEditorDdlMigration[] | undefined;

	constructor(
		private readonly storage: IEditorDdlDatabaseProvider,
		private readonly resources: readonly IEditorDdlResource[],
		private readonly now: () => Date = () => new Date(),
	) { }

	get migrations(): readonly IEditorDdlMigration[] | undefined { return this._migrations; }
	get resolved(): IEditorSchemaVersion | undefined { return this._resolved; }
	/** Migrations applied by the last `Migration Apply`; empty when the schema was already current. */
	get applied(): readonly IAppliedEditorDdlMigration[] | undefined { return this._applied; }

	async editorDdlScan(_context: IProjectOpenContext): Promise<void> {
		this._resolved = undefined;
		this._applied = undefined;
		this._migrations = scanEditorDdlResources(this.resources);
	}

	async schemaVersionResolve(_context: IProjectOpenContext): Promise<void> {
		if (!this._migrations) {
			throw new EditorDdlError('Schema Version Resolve requires Editor DDL Scan');
		}
		this._applied = undefined;
		this._resolved = await resolveEditorSchemaVersion(this.storage.database, this._migrations);
	}

	async migrationApply(_context: IProjectOpenContext): Promise<void> {
		if (!this._migrations || !this._resolved) {
			throw new EditorDdlError('Migration Apply requires Schema Version Resolve');
		}
		this._applied = await applyEditorDdlMigrations(this.storage.database, this._migrations, this._resolved, this.now);
	}
}

