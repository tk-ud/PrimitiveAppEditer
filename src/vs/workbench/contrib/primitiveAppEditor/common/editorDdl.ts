/**
 * `Editor Built-in DDL` = the Editor fixed schema.
 *
 * `Editor -> DDL Resource Scan -> Schema Version Compare -> Unapplied Migration ->
 * SQLite Transaction -> Apply`. This module owns that pipeline and supplies the
 * `Editor DDL Scan` / `Schema Version Resolve` / `Migration Apply` steps of the project `Open`
 * lifecycle. `Registry DDL` (Application Physical Schema) is generated by the Registry Service
 * and is not part of this pipeline.
 */

// #region DDL Resource Scan

/** One `ddl/<NNN>_<name>.sql` resource. */
export interface IEditorDdlResource {
	readonly name: string;
	readonly sql: string;
}

/** A scanned resource: one migration of the Editor fixed schema. */
export interface IEditorDdlMigration {
	/** Schema version reached after applying this migration (`NNN`). */
	readonly version: number;
	/** Resource name, `<NNN>_<name>.sql`. */
	readonly name: string;
	readonly sql: string;
	/** SHA-1 of `sql`; an applied migration must never change. */
	readonly checksum: string;
}

export class EditorDdlError extends Error {
	constructor(message: string) {
		super(message);
		this.name = 'EditorDdlError';
	}
}

const resourceNamePattern = /^(\d{3})_[a-z][a-z0-9]*(?:_[a-z0-9]+)*\.sql$/;

/** Keywords that start a transaction control statement. */
const transactionControlKeywords: ReadonlySet<string> = new Set(['BEGIN', 'COMMIT', 'END', 'ROLLBACK', 'SAVEPOINT', 'RELEASE']);

/**
 * Leading keyword of every top-level statement in `sql`. Comments and quoted strings /
 * identifiers are ignored, and a `CREATE TRIGGER ... BEGIN ... END` body belongs to its
 * trigger statement, so its `BEGIN` / `END` are not statements of their own.
 */
function topLevelStatementKeywords(sql: string): readonly string[] {
	const tokens = sql
		.replace(/--[^\n]*|\/\*[\s\S]*?\*\/|'(?:[^']|'')*'|"(?:[^"]|"")*"|`(?:[^`]|``)*`|\[[^\]]*\]/g, ' ')
		.match(/[A-Za-z_][A-Za-z0-9_$]*|;/g) ?? [];
	const keywords: string[] = [];
	let statement: string[] = [];
	let inTriggerBody = false;
	let atBodyStatementStart = false;
	for (const token of tokens) {
		const word = token.toUpperCase();
		if (inTriggerBody) {
			if (word === ';') {
				atBodyStatementStart = true;
				continue;
			}
			if (atBodyStatementStart && word === 'END') {
				inTriggerBody = false;
			}
			atBodyStatementStart = false;
			continue;
		}
		if (word === ';') {
			statement = [];
			continue;
		}
		if (!statement.length) {
			keywords.push(word);
		}
		statement.push(word);
		if (word === 'BEGIN' && statement[0] === 'CREATE' && (statement[1] === 'TRIGGER' || statement[2] === 'TRIGGER')) {
			inTriggerBody = true;
			atBodyStatementStart = true;
		}
	}
	return keywords;
}

/**
 * Statements a built-in resource must not contain: the migration runner owns the SQLite
 * transaction, and the SQLite schema feature is not used (logical namespaces are flat
 * `<schema>__<table>` names).
 */
const forbiddenStatements: readonly { readonly test: (sql: string) => boolean; readonly reason: string }[] = Object.freeze([
	{ test: (sql: string) => topLevelStatementKeywords(sql).some(keyword => transactionControlKeywords.has(keyword)), reason: 'transaction control is owned by Migration Apply' },
	{ test: (sql: string) => /\b(ATTACH|DETACH)\b/i.test(sql), reason: 'the SQLite schema feature is not used' },
]);

export function computeEditorDdlChecksum(sql: string): string {
	const sha = new StringSHA1();
	sha.update(sql);
	return sha.digest();
}

/**
 * `DDL Resource Scan`: validates the resources and orders them by version. Versions start at 1
 * and are contiguous; names follow `<NNN>_<name>.sql`; every resource carries DDL.
 */
export function scanEditorDdlResources(resources: readonly IEditorDdlResource[]): readonly IEditorDdlMigration[] {
	const migrations: IEditorDdlMigration[] = [];
	for (const resource of resources) {
		const match = resourceNamePattern.exec(resource.name);
		if (!match) {
			throw new EditorDdlError(`Editor DDL resource name must match ${resourceNamePattern.source}: '${resource.name}'`);
		}
		if (!resource.sql.trim()) {
			throw new EditorDdlError(`Editor DDL resource '${resource.name}' is empty`);
		}
		for (const { test, reason } of forbiddenStatements) {
			if (test(resource.sql)) {
				throw new EditorDdlError(`Editor DDL resource '${resource.name}' is rejected: ${reason}`);
			}
		}
		migrations.push(Object.freeze({
			version: Number(match[1]),
			name: resource.name,
			sql: resource.sql,
			checksum: computeEditorDdlChecksum(resource.sql),
		}));
	}
	migrations.sort((a, b) => a.version - b.version);
	migrations.forEach((migration, index) => {
		if (migration.version !== index + 1) {
			throw new EditorDdlError(`Editor DDL versions must be contiguous from 001: expected ${String(index + 1).padStart(3, '0')}, got '${migration.name}'`);
		}
	});
	return Object.freeze(migrations);
}

